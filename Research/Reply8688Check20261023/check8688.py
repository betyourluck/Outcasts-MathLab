# A13-A14: breadth-first square-source replay (procedure of >>86 section 4)
def square_source_test(p, q, tau):
    sigma = 1 if q % 4 == 3 else 3
    c = sigma * q * tau * tau
    assert c < 3 * p and (p + c) % 4 == 0
    x = (p + c) // 4
    assert 0 < x < p
    f = factor(x)
    ds = divisors({r: 2 * e for r, e in f.items()})
    for branch, target in (('II', -x), ('I', -p * x)):
        for d in ds:
            if (d - target) % c == 0:
                if branch == 'II':
                    y, z = p * (d + x) // c, p * (x * x // d + x) // c
                    assert p * (d + x) % c == 0 and p * (x * x // d + x) % c == 0
                else:
                    y, z = (d + p * x) // c, (p * p * (x * x // d) + p * x) // c
                    assert (d + p * x) % c == 0 and (p * p * (x * x // d) + p * x) % c == 0
                assert 4 * x * y * z == p * (x * y + x * z + y * z)
                return {'branch': branch, 'q': q, 'tau': tau, 'c': c, 'x': x, 'd': d, 'y': y, 'z': z}, f
    return None, f


def bfs(p):
    ell = least_nonresidue(p)
    queue, seen, parent, order = deque([ell]), {ell}, {}, []
    while queue:
        q = queue.popleft()
        sigma = 1 if q % 4 == 3 else 3
        tau = 1
        while sigma * q * tau * tau < 3 * p:
            hit, f = square_source_test(p, q, tau)
            order.append((q, tau))
            if hit:
                path, r = [], q
                while r != ell:
                    pq, pt = parent[r]
                    path.append((pq, pt, r))
                    r = pq
                return {'p': p, 'ell': ell, 'status': 'hit', 'checked': len(order), 'order': order,
                        'vertices': sorted(seen), 'path': path[::-1], 'hit': hit}
            for r in sorted(f):
                if chi(r, p) == -1 and r not in seen:
                    assert r < p
                    seen.add(r)
                    parent[r] = (q, tau)
                    queue.append(r)
            tau += 2
    return {'p': p, 'ell': ell, 'status': 'exhausted', 'checked': len(order), 'order': order, 'vertices': sorted(seen)}


