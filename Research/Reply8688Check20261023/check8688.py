def min_extra_by_levels(f, m):
    """Method (i): increase the allowed extra cost D = 0,1,2,... and enumerate all vectors
    0 <= f_q <= e_q + D with cost <= D until some product is -1 mod m. Returns (D, minimizers)."""
    qs = list(f)
    for D in range(0, 20):
        hits = []
        for es in itertools.product(*(range(f[q] + D + 1) for q in qs)):
            cost = sum(max(0, e - f[q]) for q, e in zip(qs, es))
            if cost > D:
                continue
            if math.prod(pow(q, e, m) for q, e in zip(qs, es)) % m == m - 1:
                hits.append((dict(zip(qs, es)), cost))
        if hits:
            assert all(c == D for _, c in hits)  # cost < D would have been found at an earlier level
            return D, [h for h, _ in hits]
    raise AssertionError('no word reaches -1')


def min_extra_by_dp(f, m):
    """Method (ii): per prime, exponents 0 <= f_q < ord_m(q) (reducing by the order keeps the
    residue and never raises max(0, f_q - e_q)); dynamic programming over residues."""
    best = {1 % m: 0}
    for q, e in f.items():
        o = order_mod(q, m)
        nb = {}
        for r, c in best.items():
            for k in range(o):
                v = r * pow(q, k, m) % m
                cc = c + max(0, k - e)
                if v not in nb or cc < nb[v]:
                    nb[v] = cc
        best = nb
    return best.get(m - 1), len(best)


