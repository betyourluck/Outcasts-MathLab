def trial_factor(n):
    f, q = {}, 2
    while q * q <= n:
        while n % q == 0:
            f[q] = f.get(q, 0) + 1
            n //= q
        q += 1 if q == 2 else 2
    if n > 1:
        f[n] = f.get(n, 0) + 1
    return f


def factor(n):
    a = trial_factor(n)
    b = {int(k): int(v) for k, v in sympy.factorint(n).items()}
    assert a == b, (n, a, b)
    return dict(sorted(a.items()))


def is_prime(n):
    return sympy.isprime(n) and factor(n) == {n: 1}


def chi(a, p):
    """Legendre symbol (a|p) by Euler's criterion, p odd prime."""
    k = pow(a % p, (p - 1) // 2, p)
    assert k in (0, 1, p - 1)
    return 0 if k == 0 else (1 if k == 1 else -1)


def kron_minus3(r):
    """(-3|r) for a prime r != 3: +1 iff r == 1 mod 3."""
    assert r % 3 != 0
    return 1 if r % 3 == 1 else -1


def divisors(f):
    ds = [1]
    for q, e in f.items():
        ds = [d * q ** j for d in ds for j in range(e + 1)]
    return sorted(ds)


def closure(gens, m):
    """Subgroup of (Z/m)^* generated by gens (all coprime to m)."""
    assert all(math.gcd(g, m) == 1 for g in gens)
    H = {1 % m}
    frontier = [1 % m]
    while frontier:
        nxt = []
        for h in frontier:
            for g in gens:
                v = h * g % m
                if v not in H:
                    H.add(v)
                    nxt.append(v)
        frontier = nxt
    return H


def order_mod(q, m):
    assert math.gcd(q, m) == 1
    r, k = q % m, 1
    while r != 1 % m:
        r = r * q % m
        k += 1
    return k


def val(n, r):
    assert n != 0
    n, e = abs(n), 0
    while n % r == 0:
        n //= r
        e += 1
    return e


def least_nonresidue(p):
    q = 2
    while True:
        if is_prime(q) and chi(q, p) == -1:
            return q
        q += 1


