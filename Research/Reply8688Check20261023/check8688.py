def delta_set(Pplus, mod):
    return sorted({a * pow(b, -1, mod) % mod for a in Pplus for b in Pplus})


def classify(p, q, tau):
    sigma = 1 if q % 4 == 3 else 3
    base = sigma * q
    c = base * tau * tau
    x = (p + c) // 4
    assert 4 * x == p + c and 0 < x < p and math.gcd(c, x) == 1 and chi(x, p) == -1
    f = factor(x)
    nonres = [r for r in f if chi(r, p) == -1]
    omega = sum(f[r] for r in nonres)
    Pplus = [dd for dd in divisors(f) if chi(dd, p) == 1]
    out = {'tau': tau, 'c': c, 'x': x, 'factors': f, 'omega_minus': omega, 'Pplus': Pplus, 'gcd_base_square': math.gcd(base, tau * tau)}
    if omega == 1:
        r = nonres[0]
        m = x // r
        assert f[r] == 1 and Pplus == divisors(factor(m)) if m > 1 else Pplus == [1]
        out['r'] = r
        targets = {'I': -p, 'II': -r}
        for br, tg in targets.items():
            res = {}
            for mod in (base, tau * tau, c):
                res[mod] = (tg % mod) in delta_set(Pplus, mod)
            # direct test over all d | x^2 in the full modulus
            ds2 = divisors({rr: 2 * e for rr, e in f.items()})
            direct = [dd for dd in ds2 if (dd + (p * x if br == 'I' else x)) % c == 0]
            assert bool(direct) == res[c], (tau, br)
            if res[c]:
                kind = 'success'
            elif not res[base]:
                kind = 'base'
            elif not res[tau * tau]:
                kind = 'square'
            else:
                kind = 'joint'
            out[br] = {'base_pass': res[base], 'square_pass': res[tau * tau], 'full_pass': res[c], 'class': kind, 'direct_hits': direct}
    return out


