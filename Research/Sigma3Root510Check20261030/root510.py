"""Check of the 510 root sources of p = 42698041, ell = 41 (>>103, >>104) -- see contract.md.

Own implementation; the square-source arithmetic is the one of ChildObstacles20261028/childobs.py, rewritten (not
imported). No peer code or result file is read.

Usage:
  python -I -X utf8 root510.py selftest   # 8615161 and 84525841 (ell = 17), regression against source_stages.tsv
  python -I -X utf8 root510.py cohort     # 42698041; refuses to run unless contract.md and root510.py are committed
                                          # and unchanged
stdout is the log.
"""
import sys, os, json, math, time, subprocess
import sympy

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
TSV = os.path.join(ROOT, 'Research', 'ChildObstacles20261028', 'source_stages.tsv')
COHORT = 42698041
SELFTEST = [8615161, 84525841]
CAP = 10 * 60
T0 = time.monotonic()
RAD_CHECK_TAU = 49  # K_c is generated only for tau <= 49 (contract)


def budget():
    assert time.monotonic() - T0 < CAP, 'time cap'


# ---------------------------------------------------------------- arithmetic

def trial_factor(n):
    f, q = {}, 2
    while q * q <= n:
        while n % q == 0:
            f[q] = f.get(q, 0) + 1
            n //= q
        q += 1 if q == 2 else 2
    if n > 1:
        f[n] = f.get(n, 0) + 1
    return f


def factor(n):
    a = trial_factor(n)
    b = {int(k): int(v) for k, v in sympy.factorint(n).items()}
    assert a == b, (n, a, b)
    return dict(sorted(a.items()))


def leg(a, r):
    k = pow(a % r, (r - 1) // 2, r)
    assert k in (1, r - 1), (a, r)
    return 1 if k == 1 else -1


def divisors(f):
    ds = [1]
    for r, e in f.items():
        ds = [d * r ** j for d in ds for j in range(e + 1)]
    return sorted(ds)


def least_nonresidue(p):
    for q in sympy.primerange(2, p):
        if leg(q, p) == -1:
            return q


def rad(n):
    return math.prod(factor(n)) if n > 1 else 1


def residues(f2, m, ds=None):
    """Residues mod m of the divisors of the number with factorization f2, two routes."""
    R = {1 % m}
    for g, e in f2.items():
        pw = [pow(g, j, m) for j in range(e + 1)]
        R = {v * w % m for v in R for w in pw}
    if ds is not None:
        assert {d % m for d in ds} == R
    return R


def subgroup(gens, m):
    """The subgroup of (Z/m)^x generated by gens (all units), built coset by coset."""
    K = {1 % m}
    for g in gens:
        g %= m
        if g in K:
            continue
        cosets, h = [K], g
        while h not in K:
            cosets.append({k * h % m for k in K})
            h = h * g % m
        K = set().union(*cosets)
    return K


def units(m):
    return [a for a in range(1, m) if math.gcd(a, m) == 1] if m > 1 else [0]


# ---------------------------------------------------------------- one source

def analyze(p, q, tau):
    A = 3 * q
    c = A * tau * tau
    assert q % 4 == 1 and tau % 2 == 1 and c < 3 * p and (p + c) % 4 == 0
    x = (p + c) // 4
    assert 0 < x < p and math.gcd(c, x) == 1
    f = factor(x)
    f2 = {g: 2 * e for g, e in f.items()}
    ds = divisors(f2)
    tII, tI = (-x) % c, (-p * x) % c
    Rc = residues(f2, c, ds)
    succ = {'II': tII in Rc, 'I': tI in Rc}
    o = {'tau': tau, 'c': c, 'x': x, 'f': f, 'succ': succ}
    # size lemma (>>104): a Type II success needs c <= x + 1 and k = (d + x)/c <= (x + 1)/c
    o['size_impossible'] = c > x + 1
    assert (c > x + 1) == (3 * c > p + 4)
    if succ['II']:
        assert c <= x + 1
        for d in ds:
            if (d + x) % c == 0:
                # d = u^2 v, x = u v t, gcd(u, t) = 1: u v = gcd(d, x), u + t = (d + x)/(u v), k = (u + t)/c
                ut = (d + x) // math.gcd(d, x)
                assert ut % c == 0 and ut <= x + 1, (tau, d)
    # modulus A = 3q (>>103)
    G = units(A)
    K = subgroup(list(f), A)
    RA = residues(f2, A, ds)
    a = any(g % 3 == 2 for g in f)
    sq = {u * u % A for u in G}
    KG2 = {k * s % A for k in K for s in sq}
    b = len(KG2) == len(G)
    cc = (len(G) // len(K)) % 2 == 1
    d_ = (A - 1) in K
    e = (-x) % A in K
    assert x % 3 == 1 and leg(x, q) == -1, (tau,)
    assert a == b == cc == d_ == e, (p, q, tau, a, b, cc, d_, e)
    I_in = (-p * x) % A in K
    assert I_in == (a and (4 % A) in K), (p, q, tau)
    if x % 2 == 0:
        assert e and I_in
    o['A'] = {'K_order': len(K), 'gII': e, 'gI': I_in, 'rII': (-x) % A in RA, 'rI': (-p * x) % A in RA,
              'has_2mod3': a}
    # radical of c (>>104)
    Rr = rad(c)
    KR = subgroup(list(f), Rr)
    RR = residues(f2, Rr, ds)
    o['R'] = {'rad': Rr, 'K_order': len(KR), 'gII': (-x) % Rr in KR, 'rII': (-x) % Rr in RR,
              'rI': (-p * x) % Rr in RR, 'm1': (Rr - 1) in KR}
    assert o['R']['gII'] == o['R']['m1'], (tau,)
    if succ['II']:
        assert o['R']['rII'] and o['A']['rII']
    if tau <= RAD_CHECK_TAU:
        Kc = subgroup(list(f), c)
        o['Kc'] = {'x': tII in Kc, 'm1': (c - 1) in Kc}
        assert o['Kc']['x'] == o['Kc']['m1'] == o['R']['m1'] == o['R']['gII'], (tau, o['Kc'], o['R'])
    return o


def classify(o):
    A, R = o['A'], o['R']
    if o['succ']['II']:
        b = 'B4'
    elif not A['gII']:
        b = 'B1'
    elif not A['rII']:
        b = 'B2'
    else:
        b = 'B3'
    if o['size_impossible']:
        s = 'S1'
    elif not R['gII']:
        s = 'S2'
    elif not R['rII']:
        s = 'S3'
    else:
        s = 'S4'
    x = 'X_gfail' if not R['gII'] else ('X_nodiv' if not R['rII'] else 'X_div')
    return b, s, x


def run(p):
    assert sympy.isprime(p) and p % 24 == 1
    q = least_nonresidue(p)
    taus = []
    t = 1
    while 3 * q * t * t < 3 * p:
        taus.append(t)
        t += 2
    rows = []
    for t in taus:
        budget()
        o = analyze(p, q, t)
        o['class'] = classify(o)
        rows.append(o)
    return q, rows


def tally(rows):
    out = {}
    for o in rows:
        b, s, x = o['class']
        for k in (b, s, x, f'{x}&{"S1" if s == "S1" else "notS1"}'):
            out[k] = out.get(k, 0) + 1
    out['succ_II'] = sum(o['succ']['II'] for o in rows)
    out['succ_I'] = sum(o['succ']['I'] for o in rows)
    out['typeI_rad_pass_full_fail'] = [o['tau'] for o in rows if o['R']['rI'] and not o['succ']['I']]
    out['rad_checked'] = sum('Kc' in o for o in rows)
    return dict(sorted(out.items(), key=lambda kv: kv[0]))


def git(*a):
    return subprocess.run(['git', *a], cwd=ROOT, capture_output=True, text=True).stdout.strip()


def committed_clean(paths):
    for pth in paths:
        rel = os.path.relpath(pth, ROOT).replace('\\', '/')
        if git('ls-files', rel) != rel or git('status', '--porcelain', '--', rel):
            return False
    return True


def main():
    mode = sys.argv[1]
    print('python', sys.version.split()[0], 'sympy', sympy.__version__, 'HEAD', git('rev-parse', '--short', 'HEAD'))
    if mode == 'selftest':
        stored = {}
        with open(TSV, encoding='utf-8') as fh:
            next(fh)
            for line in fh:
                pp, role, q, tau, II, I = line.rstrip('\n').split('\t')
                if role == 'root':
                    stored[(int(pp), int(tau))] = (II, I)
        res = {}
        for p in SELFTEST:
            q, rows = run(p)
            assert q == 17
            n = 0
            for o in rows:
                II, I = stored[(p, o['tau'])]
                assert (not o['A']['rII']) == II.startswith('base'), (p, o['tau'], II)
                assert (not o['A']['gII']) == (II == 'base:real'), (p, o['tau'], II)
                assert (not o['A']['rI']) == I.startswith('base'), (p, o['tau'], I)
                assert o['succ']['II'] == (II == 'success') and o['succ']['I'] == (I == 'success'), (p, o['tau'])
                n += 1
            assert n == sum(1 for k in stored if k[0] == p)
            res[p] = {'ell': q, 'n': len(rows), 'regression_rows': n, 'tally': tally(rows)}
            print(p, 'ell', q, 'sources', len(rows), 'regression rows', n, json.dumps(res[p]['tally']))
        with open(os.path.join(HERE, 'selftest_results.json'), 'w', encoding='utf-8', newline='\n') as fh:
            json.dump(res, fh, indent=1)
            fh.write('\n')
    elif mode == 'cohort':
        assert committed_clean([os.path.join(HERE, 'contract.md'), os.path.abspath(__file__)]), \
            'commit contract.md and root510.py first'
        p = COHORT
        q, rows = run(p)
        assert q == 41 and len(rows) == 510
        tl = tally(rows)
        ex = next(o for o in rows if o['tau'] == 11)
        RA11 = sorted(residues({g: 2 * e for g, e in ex['f'].items()}, 123))
        example = {'tau': 11, 'c': ex['c'], 'x': ex['x'], 'f': ex['f'], 'K_order': ex['A']['K_order'],
                   'minus_x_mod_123': (-ex['x']) % 123, 'R123': RA11}
        print('p', p, 'ell', q, 'sources', len(rows))
        print('tally', json.dumps(tl))
        print('example', json.dumps(example))
        expected = {'B1': 259, 'B2': 224, 'B3': 27, 'B4': 0, 'S1': 340, 'S2': 134, 'S3': 36, 'S4': 0,
                    'X_gfail': 411, 'X_gfail&S1': 277, 'X_nodiv': 99, 'X_nodiv&S1': 63, 'X_div': 0}
        ex_expected = {'c': 14883, 'x': 10678231, 'f': {347: 1, 30773: 1}, 'K_order': 80, 'minus_x_mod_123': 14,
                       'R123': [1, 23, 37, 47, 62, 73, 101, 109, 115]}
        cmp = []
        for k, v in expected.items():
            got = tl.get(k, 0)
            cmp.append((k, v, got, 'OK' if v == got else 'DIFF'))
        for k, v in ex_expected.items():
            got = example[k]
            cmp.append(('tau11.' + k, v, got, 'OK' if v == got else 'DIFF'))
        got = tl['typeI_rad_pass_full_fail']
        cmp.append(('typeI_rad_pass_full_fail', [27, 81, 135, 459], got, 'OK' if got == [27, 81, 135, 459] else 'DIFF'))
        min_S1 = min(o['tau'] for o in rows if o['size_impossible'])
        cmp.append(('min tau of S1', 341, min_S1, 'OK' if min_S1 == 341 else 'DIFF'))
        for k, v, g, s in cmp:
            print(s, k, 'expected', v, 'got', g)
        print('OK', sum(s == 'OK' for *_, s in cmp), 'DIFF', sum(s == 'DIFF' for *_, s in cmp))
        out = {'p': p, 'ell': q, 'n_sources': len(rows), 'tally': tl, 'example_tau11': example,
               'comparison': [{'item': k, 'expected': v, 'got': g, 'status': s} for k, v, g, s in cmp],
               'rows': [{'tau': o['tau'], 'c': o['c'], 'x': o['x'], 'f': o['f'], 'succ': o['succ'],
                         'size_impossible': o['size_impossible'], 'mod123': o['A'], 'rad': o['R'],
                         'Kc': o.get('Kc'), 'class': o['class']} for o in rows]}
        with open(os.path.join(HERE, 'results.json'), 'w', encoding='utf-8', newline='\n') as fh:
            json.dump(out, fh, indent=1, default=str)
            fh.write('\n')
    print('seconds', round(time.monotonic() - T0, 2))


if __name__ == '__main__':
    main()
